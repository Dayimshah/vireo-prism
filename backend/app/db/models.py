# ---------------------------------------------------------------------------
# Naming convention
#
# Applied to any constraint or index created without an explicit name. Every
# object in the migrations *is* explicitly named, so this exists to keep
# autogenerated future objects consistent rather than letting PostgreSQL invent
# names like `users_country_id_fkey1`.
# ---------------------------------------------------------------------------
NAMING_CONVENTION: Final[dict[str, str]] = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s",
    "pk": "pk_%(table_name)s",
}

#: Schema holding the 13 source-of-truth tables.
CORE_SCHEMA: Final[str] = "core"

#: Schema holding derived materialized views. Named here for documentation and
#: for the repositories that reference it in raw SQL.
ANALYTICS_SCHEMA: Final[str] = "analytics"


class Base(DeclarativeBase):
    """Declarative base for every Prism table.

    ``MetaData.schema`` defaults all tables to ``core``, which keeps the schema
    qualifier out of thirteen ``__table_args__`` blocks. Alembic's bookkeeping
    table stays in ``public`` via ``version_table_schema=None`` in ``env.py``.
    """

    metadata = MetaData(naming_convention=NAMING_CONVENTION, schema=CORE_SCHEMA)

    type_annotation_map = {  # noqa: RUF012 - SQLAlchemy reads this as a plain dict
        Decimal: Numeric,
        datetime: DateTime(timezone=True),
    }


