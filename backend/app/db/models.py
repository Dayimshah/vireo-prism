class User(Base):
    """A registered Vireo account.

    ``is_premium``, ``last_seen_at`` and ``churned_at`` are current-state columns
    maintained by the seeder as the simulation advances. They duplicate
    information recoverable from ``subscriptions`` and ``events``, and exist
    because "how many premium users right now" is asked on every page load and
    should not require a correlated subquery over subscription history.
    """

    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint(
            "gender IN ('male', 'female', 'non_binary', 'undisclosed')", name="ck_users_gender"
        ),
        CheckConstraint("age BETWEEN 13 AND 90", name="ck_users_age_range"),
        CheckConstraint("signup_date <= CURRENT_DATE", name="ck_users_no_future_signup"),
        CheckConstraint(
            "churned_at IS NULL OR churned_at >= signup_date", name="ck_users_churn_after_signup"
        ),
        CheckConstraint(
            r"app_version ~ '^[0-9]+\.[0-9]+\.[0-9]+$'", name="ck_users_app_version_semver"
        ),
        Index("ix_users_signup_date", "signup_date"),
        Index("ix_users_country", "country_id"),
        Index("ix_users_channel", "channel_id"),
        Index("ix_users_persona", "persona_id"),
        Index("ix_users_device", "device_id"),
        Index("ix_users_premium", "user_id", postgresql_where=text("is_premium")),
        Index(
            "ix_users_churned_at", "churned_at", postgresql_where=text("churned_at IS NOT NULL")
        ),
        Index(
            "ix_users_last_seen",
            "last_seen_at",
            postgresql_where=text("last_seen_at IS NOT NULL"),
        ),
        Index("ix_users_signup_channel", "signup_date", "channel_id"),
        {"comment": "Vireo subscriber base. One row per registered account."},
    )

    user_id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    signup_date: Mapped[date] = mapped_column(Date)

    country_id: Mapped[int] = mapped_column(
        SmallInteger, ForeignKey("countries.country_id", name="fk_users_country", onupdate="CASCADE")
    )
    device_id: Mapped[int] = mapped_column(
        SmallInteger,
        ForeignKey("devices.device_id", name="fk_users_device", onupdate="CASCADE"),
        comment="Device used at signup. Sessions carry their own device_id.",
    )
    channel_id: Mapped[int] = mapped_column(
        SmallInteger,
        ForeignKey(
            "marketing_channels.channel_id", name="fk_users_channel", onupdate="CASCADE"
        ),
    )
    persona_id: Mapped[int] = mapped_column(
        SmallInteger, ForeignKey("personas.persona_id", name="fk_users_persona", onupdate="CASCADE")
    )

    is_premium: Mapped[bool] = mapped_column(
        Boolean,
        server_default=text("false"),
        comment="Current paid state. Denormalised from subscriptions for read speed.",
    )
    gender: Mapped[str] = mapped_column(String(16))
    age: Mapped[int] = mapped_column(SmallInteger)
    app_version: Mapped[str] = mapped_column(String(12))
    last_seen_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    churned_at: Mapped[date | None] = mapped_column(
        Date, comment="Date the user was classified as churned. NULL means active."
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    # lazy="raise" throughout: these exist for ORM ergonomics in tests and
    # scripts. The read path uses named SQL, and an accidental lazy load inside a
    # loop should fail loudly rather than become an N+1.
    country: Mapped[Country] = relationship(lazy="raise")
    device: Mapped[Device] = relationship(lazy="raise")
    channel: Mapped[MarketingChannel] = relationship(lazy="raise")
    persona: Mapped[Persona] = relationship(lazy="raise")


