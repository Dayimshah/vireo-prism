"""SQLAlchemy 2.0 declarative models for the Prism warehouse.

Role of this module
-------------------
These models are the *typed description* of the schema, not its definition. The
Alembic revisions in ``alembic/versions/`` are authoritative for DDL; this file
mirrors them so that:

* ``alembic revision --autogenerate`` has something to diff against, and any
  accidental drift between code and database shows up as a proposed migration;
* the seeder and tests get real type checking on column names and types;
* the ER diagram and data dictionary in ``docs/`` can be generated from metadata.

The read path does **not** go through the ORM. Repositories execute named SQL
from ``app/sql/queries/`` via SQLAlchemy Core, because these are analytical
queries — window functions, ``FILTER`` clauses, date spines, lateral joins —
that the ORM would only obscure. Using the ORM for aggregate analytics also
tends to produce accidental N+1 patterns, which is why every relationship below
is declared ``lazy="raise"``: touching one outside an explicit eager load raises
instead of silently issuing a query per row.

Materialized views are absent by design. ``analytics.mv_*`` objects are created
in revision 0006 and queried as raw SQL; SQLAlchemy cannot model a materialized
view, and ``alembic/env.py`` excludes the whole ``analytics`` schema from
autogenerate so it never proposes dropping them.
"""

